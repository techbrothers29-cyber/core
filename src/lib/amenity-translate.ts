function titleCasePt(s: string): string {
  if (!s) return s;
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function translateAmenity(raw: string): string {
  if (!raw || typeof raw !== "string") return raw;
  const trimmed = raw.trim();
  const key = trimmed.toLowerCase();
  if (MAP[key]) return MAP[key];

  // Try " - free"/" - paid" suffixes
  const m = key.match(/^(.*)\s*[-–]\s*(free|paid)$/);
  if (m && MAP[m[1].trim()]) {
    return `${MAP[m[1].trim()]} (${m[2] === "free" ? "grátis" : "pago"})`;
  }

  // Try without parentheticals
  const noParen = key.replace(/\s*\(.+?\)\s*/g, "").trim();
  if (noParen !== key && MAP[noParen]) return MAP[noParen];

  return titleCasePt(trimmed);
}

